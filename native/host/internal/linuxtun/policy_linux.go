//go:build linux && !android

// Package linuxtun manages dedicated Linux TUN resources and their recovery.
// It does not authorize elevation or accept arbitrary routing configuration.
package linuxtun

import (
	"encoding/binary"
	"errors"
	"net/netip"
	"strings"

	"golang.org/x/sys/unix"
	"rainlink.local/host/internal/linuxnet"
	"rainlink.local/host/internal/tunconfig"
)

const (
	// RuleSpan is the complete priority range reserved by locked sing-tun.
	RuleSpan        = 11
	minimumTable    = 65536
	maximumTable    = 0x7fffffff
	minimumPriority = 10000
	maximumPriority = 32755 // Keep the full range before the ordinary main rule.
)

// Specification names only dedicated resources, never a user node or secret.
type Specification struct {
	Name     string `json:"name"`
	Table    uint32 `json:"table"`
	Priority uint32 `json:"priority"`
}

func (s Specification) validate() error {
	if !strings.HasPrefix(s.Name, "rl-") || len(s.Name) < 4 || len(s.Name) >= unix.IFNAMSIZ ||
		s.Table < minimumTable || s.Table > maximumTable || s.Priority < minimumPriority || s.Priority > maximumPriority {
		return errors.New("invalid dedicated TUN resource specification")
	}
	for _, value := range s.Name[3:] {
		if !(value >= 'a' && value <= 'z' || value >= '0' && value <= '9' || value == '-') {
			return errors.New("invalid dedicated TUN interface name")
		}
	}
	return nil
}

func integerAttribute(kind uint16, value uint32) linuxnet.Attribute {
	data := make([]byte, 4)
	binary.NativeEndian.PutUint32(data, value)
	return linuxnet.Attribute{Type: kind, Value: data}
}

func inputAttribute(name string) linuxnet.Attribute {
	return linuxnet.Attribute{Type: unix.FRA_IIFNAME, Value: append([]byte(name), 0)}
}

func policyRule(family uint8, priority, table uint32, action uint8, attributes ...linuxnet.Attribute) linuxnet.Rule {
	prefix := netip.PrefixFrom(netip.IPv4Unspecified(), 0)
	if family == unix.AF_INET6 {
		prefix = netip.PrefixFrom(netip.IPv6Unspecified(), 0)
	}
	base := []linuxnet.Attribute{integerAttribute(unix.FRA_PRIORITY, priority), integerAttribute(unix.FRA_TABLE, table)}
	return linuxnet.Rule{Family: family, Priority: priority, Table: table, Action: action,
		Source: prefix, Destination: prefix, Attributes: append(base, attributes...)}
}

func withSource(rule linuxnet.Rule, source netip.Prefix) linuxnet.Rule {
	rule.Source = source
	rule.Attributes = append(rule.Attributes, linuxnet.Attribute{Type: unix.FRA_SRC, Value: source.Addr().AsSlice()})
	return rule
}

// ExpectedRules describes every rule generated by the locked dual-stack Linux
// configuration: auto_route, strict_route, no auto_redirect or extra filters.
// It is derived before core start so a crash during partial setup is recoverable.
func (s Specification) ExpectedRules() ([]linuxnet.Rule, error) {
	return s.expectedRules(tunconfig.RuleProtocol)
}

func (s Specification) expectedRules(protocol uint8) ([]linuxnet.Rule, error) {
	if err := s.validate(); err != nil {
		return nil, err
	}
	address4 := netip.MustParsePrefix(tunconfig.IPv4Address).Masked()
	address6 := netip.MustParsePrefix(tunconfig.IPv6Address).Masked()
	var rules []linuxnet.Rule
	lookup := func(family uint8, offset, table uint32, attributes ...linuxnet.Attribute) linuxnet.Rule {
		return policyRule(family, s.Priority+offset, table, unix.FR_ACT_TO_TBL, attributes...)
	}
	jump := func(family uint8, offset uint32, input string) linuxnet.Rule {
		return policyRule(family, s.Priority+offset, 0, unix.FR_ACT_GOTO,
			inputAttribute(input), integerAttribute(unix.FRA_GOTO, s.Priority+RuleSpan-1))
	}
	local4 := lookup(unix.AF_INET, 0, s.Table)
	local4.Destination = address4
	local4.Attributes = append(local4.Attributes, linuxnet.Attribute{Type: unix.FRA_DST, Value: address4.Addr().AsSlice()})
	rules = append(rules, local4)
	for _, family := range []uint8{unix.AF_INET, unix.AF_INET6} {
		offset := uint32(1)
		if family == unix.AF_INET6 {
			offset = 0
		}
		rules = append(rules, lookup(family, offset, s.Table, integerAttribute(unix.FRA_SUPPRESS_PREFIXLEN, 0)))
		ports := make([]byte, 4)
		binary.NativeEndian.PutUint16(ports, 53)
		binary.NativeEndian.PutUint16(ports[2:], 53)
		dns := lookup(family, offset+1, unix.RT_TABLE_MAIN,
			integerAttribute(unix.FRA_SUPPRESS_PREFIXLEN, 0), linuxnet.Attribute{Type: unix.FRA_DPORT_RANGE, Value: ports})
		dns.Flags = unix.FIB_RULE_INVERT
		rules = append(rules, dns, jump(family, offset+1, s.Name))
	}
	nonLocal := lookup(unix.AF_INET, 3, s.Table, inputAttribute("lo"))
	nonLocal.Flags = unix.FIB_RULE_INVERT
	rules = append(rules, nonLocal,
		withSource(lookup(unix.AF_INET, 3, s.Table, inputAttribute("lo")), netip.MustParsePrefix("0.0.0.0/32")),
		withSource(lookup(unix.AF_INET, 3, s.Table, inputAttribute("lo")), address4),
		withSource(jump(unix.AF_INET6, 1, "lo"), netip.MustParsePrefix("::/1")),
		withSource(jump(unix.AF_INET6, 1, "lo"), netip.MustParsePrefix("8000::/1")),
		withSource(lookup(unix.AF_INET6, 2, s.Table, inputAttribute("lo")), address6),
		lookup(unix.AF_INET6, 3, s.Table),
		policyRule(unix.AF_INET, s.Priority+RuleSpan-1, 0, unix.FR_ACT_NOP),
		policyRule(unix.AF_INET6, s.Priority+RuleSpan-1, 0, unix.FR_ACT_NOP))
	for index := range rules {
		rules[index].Attributes = append(rules[index].Attributes, linuxnet.Attribute{Type: unix.FRA_PROTOCOL, Value: []byte{protocol}})
	}
	return rules, nil
}
