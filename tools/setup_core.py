"""Build pinned sing-box with RainLink's certificate-pin extension.

Go overlays leave the upstream module cache untouched. The upstream module sum,
modified-file hashes, toolchain and resulting executable are all pinned.
"""
import argparse
import hashlib
import json
import os
import platform
from pathlib import Path
import shutil
import subprocess
import zipfile

from core_linux_tun import prepare_linux_tun


ROOT = Path(__file__).resolve().parent.parent
LOCK_PATH = ROOT / "tools/core.lock.json"


def digest(data):
    return hashlib.sha256(data).hexdigest()


def replace_once(text, old, new):
    if text.count(old) != 1:
        raise RuntimeError("Pinned upstream source no longer matches extension")
    return text.replace(old, new, 1)


def write_host_core_hash(lock):
    generated = ROOT / "native/host/internal/coreprocess/core_hash_generated.go"
    targets = {lock["platform"]: lock["binarySha256"]}
    targets.update({name: entry["binarySha256"]
                    for name, entry in lock.get("additionalPlatforms", {}).items()})
    generated.write_bytes((
        "// Code generated by tools/setup_core.py; DO NOT EDIT.\n"
        "package coreprocess\n\n"
        'var expectedCoreSHA256 = map[string]string{\n' +
        ''.join('\t"' + name + '": "' + value + '",\n'
                for name, value in sorted(targets.items())) + '}\n').encode("utf-8"))
    subprocess.run(["gofmt", "-w", str(generated)], check=True, timeout=30)


def native_platform():
    system = {"Windows": "windows", "Linux": "linux", "Darwin": "darwin"}.get(platform.system())
    arch = {"AMD64": "amd64", "x86_64": "amd64", "arm64": "arm64", "aarch64": "arm64"}.get(platform.machine())
    if system is None or arch is None:
        raise RuntimeError("Unsupported core build host")
    return system + "-" + arch


def prepare_sources(lock, env, managed_tun=False):
    """Verify and stage upstream source and the shared certificate overlay."""
    module = subprocess.run(
        ["go", "mod", "download", "-json", lock["module"] + "@" + lock["upstreamVersion"]],
        cwd=ROOT / "native/host", env=env, check=True, capture_output=True, text=True, timeout=120)
    source = json.loads(module.stdout)
    if source.get("Sum") != lock["moduleSum"]:
        raise RuntimeError("Core source module checksum mismatch")
    variant = "linux-tun-" if managed_tun else ""
    source_dir = ROOT / "build/core-source" / (variant + lock["upstreamVersion"])
    # Go forbids overlays inside GOMODCACHE; use a disposable verified copy.
    shutil.copytree(Path(source["Dir"]), source_dir, dirs_exist_ok=True,
                    copy_function=shutil.copyfile)
    overlay_dir = ROOT / "build/core-overlay" / ("linux-tun" if managed_tun else "tls")
    overlay_dir.mkdir(parents=True, exist_ok=True)
    replacements = {}
    for relative, expected in lock["upstreamFiles"].items():
        original = source_dir / relative
        raw = original.read_bytes()
        if digest(raw) != expected:
            raise RuntimeError("Core source file checksum mismatch: " + relative)
        content = raw.decode("utf-8")
        if relative == "option/tls.go":
            content = replace_once(content, "type OutboundTLSOptions struct {",
                'type OutboundTLSOptions struct {\n\tRainLinkCertificateSHA256 string `json:"rainlink_certificate_sha256,omitempty"`')
        elif relative == "common/tls/std_client.go":
            content = replace_once(content, "\tstdConfig := &STDClientConfig{",
                "\tif err := applyRainLinkCertificatePin(&tlsConfig, options.RainLinkCertificateSHA256); err != nil {\n"
                "\t\treturn nil, err\n\t}\n\tstdConfig := &STDClientConfig{")
        modified = overlay_dir / relative.replace("/", "_")
        modified.write_bytes(content.encode("utf-8"))
        replacements[str(original)] = str(modified)
    for extension in sorted((ROOT / "native/core").glob("*.go")):
        replacements[str(source_dir / "common/tls" / extension.name)] = str(extension)
    if managed_tun:
        prepare_linux_tun(lock, env, source_dir, replacements, digest, replace_once)
    subprocess.run(["gofmt", "-w", *[v for v in replacements.values()
                                   if Path(v).parent == overlay_dir]], check=True, timeout=30)
    overlay_path = overlay_dir / "overlay.json"
    overlay_path.write_text(json.dumps({"Replace": replacements}, indent=2), encoding="utf-8")
    return source, source_dir, overlay_path, replacements


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--update-lock", action="store_true",
                        help="Rebuild and record the reviewed executable checksum")
    parser.add_argument("--platform", default=native_platform(),
                        choices=["windows-amd64", "linux-amd64", "linux-arm64", "darwin-amd64", "darwin-arm64"],
                        help="Core target; extension tests run on the build host")
    args = parser.parse_args()
    lock = json.loads(LOCK_PATH.read_text(encoding="utf-8"))
    target_platform = args.platform
    goos, goarch = target_platform.split("-")
    primary = target_platform == lock["platform"]
    target_lock = lock if primary else lock.get("additionalPlatforms", {}).get(target_platform, {})
    expected_hash = target_lock.get("binarySha256")
    version = target_lock.get("version", lock["version"])
    managed_tun = goos == "linux"
    if managed_tun:
        version = lock["linuxTUN"]["version"]
        if target_lock.get("version", version) != version:
            raise RuntimeError("Linux core version does not match its managed TUN extension")
    if expected_hash is None and not args.update_lock:
        raise RuntimeError("Target has no reviewed checksum; build it once with --update-lock")
    target = ROOT / "build/host"
    if not primary:
        target /= target_platform
    binary_name = "sing-box.exe" if goos == "windows" else "sing-box"
    binary = target / binary_name
    license_path = target / "sing-box-LICENSE.txt"
    evidence_path = target / "sing-box-build.json"
    source_archive = target / "sing-box-source.zip"
    recipe = {"lock": lock, "platform": target_platform, "builder": digest(Path(__file__).read_bytes()),
              "linuxBuilder": digest((ROOT / "tools/core_linux_tun.py").read_bytes()),
              "extension": {p.relative_to(ROOT / "native/core").as_posix(): digest(p.read_bytes())
                            for p in sorted((ROOT / "native/core").rglob("*")) if p.is_file()}}
    recipe_hash = digest(json.dumps(recipe, sort_keys=True).encode())
    managed_tests = ROOT / "build/core-tests" / target_platform / "sing-tun.test"
    if (not args.update_lock and binary.exists() and license_path.exists()
            and evidence_path.exists() and source_archive.exists()
            and digest(binary.read_bytes()) == expected_hash
            and digest(source_archive.read_bytes()) == json.loads(evidence_path.read_text(encoding="utf-8")).get("sourceArchiveSha256")
            and digest(license_path.read_bytes()) == json.loads(evidence_path.read_text(encoding="utf-8")).get("licenseSha256")
            and json.loads(evidence_path.read_text(encoding="utf-8")).get("recipeSha256") == recipe_hash
            and (not managed_tun or managed_tests.exists() and digest(managed_tests.read_bytes()) ==
                 json.loads(evidence_path.read_text(encoding="utf-8")).get("managedTunTestSha256"))):
        print(f"sing-box {version} verified")
        write_host_core_hash(lock)
        return

    env = os.environ.copy()
    env.update(GOTOOLCHAIN=lock["goVersion"], GOOS=goos, GOARCH=goarch, CGO_ENABLED="0")
    source, source_dir, overlay_path, replacements = prepare_sources(lock, env, managed_tun=managed_tun)
    common = ["-overlay", str(overlay_path), "-mod=readonly", "-tags", ",".join(lock["tags"])]
    test_env = env.copy()
    test_env["GOOS"], test_env["GOARCH"] = native_platform().split("-")
    subprocess.run(["go", "test", *common, "./common/tls", "-run", "^TestRainLink", "-count=1"],
                   cwd=source_dir, env=test_env, check=True, timeout=600)
    managed_test_status = "not applicable"
    if managed_tun:
        tests = managed_tests
        tests.parent.mkdir(parents=True, exist_ok=True)
        subprocess.run(["go", "test", *common, "-c", "-o", str(tests), "github.com/sagernet/sing-tun"],
                       cwd=source_dir, env=env, check=True, timeout=600)
        managed_test_status = "compiled; execute with isolated Linux network QA"
        if target_platform == native_platform():
            subprocess.run([str(tests), "-test.run=^TestRainLink", "-test.v"], check=True, timeout=60)
            managed_test_status = "passed on build host"
    target.mkdir(parents=True, exist_ok=True)
    temporary = target / (binary_name + ".build")
    subprocess.run(["go", "build", *common, "-trimpath", "-buildvcs=false",
                    "-ldflags", "-s -w -buildid= -X github.com/sagernet/sing-box/constant.Version=" + version,
                    "-o", str(temporary), "./cmd/sing-box"], cwd=source_dir, env=env, check=True, timeout=600)
    actual_hash = digest(temporary.read_bytes())
    if args.update_lock:
        if primary:
            lock["binarySha256"] = actual_hash
        else:
            lock.setdefault("additionalPlatforms", {}).setdefault(target_platform, {})["binarySha256"] = actual_hash
            if managed_tun:
                lock["additionalPlatforms"][target_platform]["version"] = version
        LOCK_PATH.write_text(json.dumps(lock, indent=2) + "\n", encoding="utf-8")
        recipe["lock"] = lock
        recipe_hash = digest(json.dumps(recipe, sort_keys=True).encode())
    elif actual_hash != expected_hash:
        raise RuntimeError("Built core checksum mismatch; review source/toolchain before updating the lock")
    temporary.replace(binary)
    license_path.write_bytes((source_dir / "LICENSE").read_bytes())
    with zipfile.ZipFile(source_archive, "w", compression=zipfile.ZIP_DEFLATED) as archive:
        for item in sorted(source_dir.rglob("*")):
            if item.is_file():
                archive.write(replacements.get(str(item), item), str(item.relative_to(source_dir)))
        for original, modified in replacements.items():
            if not Path(original).exists():
                archive.write(modified, str(Path(original).relative_to(source_dir)))
        archive.write(ROOT / "native/core/README.md", "RAINLINK-CHANGES.md")
        archive.writestr("RAINLINK-BUILD.txt",
            "Toolchain: " + lock["goVersion"] + "; GOOS=" + goos + "; GOARCH=" + goarch + "; CGO_ENABLED=0\n"
            "Certificate extension tests ran on " + native_platform() + "\n"
            "go test -mod=readonly -tags " + ",".join(lock["tags"]) + " ./common/tls -run ^TestRainLink\n"
            "go build -mod=readonly -trimpath -buildvcs=false -tags " + ",".join(lock["tags"]) +
            ' -ldflags "-s -w -buildid= -X github.com/sagernet/sing-box/constant.Version=' +
            version + '" -o ' + binary_name + ' ./cmd/sing-box\n')
    evidence_path.write_text(json.dumps({"version": version, "platform": target_platform,
                                         "extensionTestsPlatform": native_platform(), "moduleSum": source["Sum"],
                                         "managedTun": managed_tun, "managedTunTests": managed_test_status,
                                         "managedTunTestSha256": digest(managed_tests.read_bytes()) if managed_tun else None,
                                         "sourceArchiveSha256": digest(source_archive.read_bytes()), "licenseSha256": digest(license_path.read_bytes()),
                                         "recipeSha256": recipe_hash, "binarySha256": actual_hash},
                                        indent=2) + "\n", encoding="utf-8")
    print(f"sing-box {version} built and verified: {actual_hash}")
    write_host_core_hash(lock)


if __name__ == "__main__":
    main()
